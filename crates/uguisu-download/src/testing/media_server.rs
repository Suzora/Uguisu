//! A local HTTP server that simulates the ways media hosts behave and
//! misbehave, so downloads can be tested offline and deterministically on
//! every platform. Bodies are generated from a seed (never stored), so any
//! size is available and the expected hash is computable.
//!
//! Routes (`{size}` in bytes):
//!
//! | Path | Behaviour |
//! |---|---|
//! | `/normal/{size}`, `/range/{size}` | 200/206, `Accept-Ranges: bytes`, strong ETag, honours `Range` and `If-Range` |
//! | `/weak-etag/{size}` | like `/range` but with a weak ETag |
//! | `/no-range/{size}` | ignores `Range` (always 200, no `Accept-Ranges`) |
//! | `/no-length/{size}` | chunked transfer, no `Content-Length` |
//! | `/changed-etag/{size}` | the ETag changes on every request (an `If-Range` never matches) |
//! | `/redirect/{status}/{hops}/{size}` | `hops` redirects of `status` (301/302/307/308) ending at `/range/{size}` |
//! | `/redirect-private/{target}` | 302 to `metadata`, `lan` or `loopback` private addresses |
//! | `/status/{code}` | that status (429/503 carry `Retry-After: 1`) |
//! | `/rate-limit/{size}` | first request 429 + `Retry-After: 1`, then `/range` |
//! | `/flaky/{fail}/{size}` | first `fail` requests 503, then `/range` |
//! | `/truncate/{size}/{at}` | declares `size`, sends `at` bytes, then closes |
//! | `/disconnect/{size}/{at}` | declares `size`, sends `at` bytes, then fails the stream |
//! | `/stall/{size}/{after}` | sends `after` bytes, then never sends more |
//! | `/slow/{size}/{bps}` | paced body (`bps` bytes per second) |
//! | `/gzip/{size}` | `Content-Encoding: gzip` header on an unencoded body |
//! | `/content-range-bad/{size}` | 206 with a malformed `Content-Range` |
//! | `/range-wrong-start/{size}` | 206 whose `Content-Range` starts one byte early |
//!
//! Every request is recorded ([`MediaServer::requests`]) and the server
//! tracks the peak number of concurrent bodies per route prefix
//! ([`MediaServer::max_concurrent`]).

