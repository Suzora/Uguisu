/// The running scenario server.
pub struct MediaServer {
    base: String,
    shared: Arc<Shared>,
    stop: CancellationToken,
    task: Option<tokio::task::JoinHandle<()>>,
}

impl std::fmt::Debug for MediaServer {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("MediaServer")
            .field("base", &self.base)
            .finish_non_exhaustive()
    }
}

impl MediaServer {
    /// Starts the server on an ephemeral loopback port.
    pub async fn start() -> Self {
        let shared = Arc::new(Shared::default());
        let state = AppState {
            shared: Arc::clone(&shared),
        };
        let app = Router::new()
            .route("/range/{size}", get(range))
            .route("/normal/{size}", get(normal))
            .route("/weak-etag/{size}", get(weak_etag))
            .route("/no-range/{size}", get(no_range))
            .route("/no-length/{size}", get(no_length))
            .route("/changed-etag/{size}", get(changed_etag))
            .route("/redirect/{status}/{hops}/{size}", get(redirect))
            .route("/redirect-private/{target}", get(redirect_private))
            .route("/status/{code}", get(status))
            .route("/rate-limit/{size}", get(rate_limit))
            .route("/flaky/{fail}/{size}", get(flaky))
            .route("/truncate/{size}/{at}", get(truncate))
            .route("/disconnect/{size}/{at}", get(disconnect))
            .route("/stall/{size}/{after}", get(stall))
            .route("/slow/{size}/{bps}", get(slow))
            .route("/gzip/{size}", get(gzip))
            .route("/content-range-bad/{size}", get(content_range_bad))
            .route("/range-wrong-start/{size}", get(range_wrong_start))
            .with_state(state);
        let listener = tokio::net::TcpListener::bind("127.0.0.1:0")
            .await
            .expect("bind loopback");
        let base = format!("http://{}", listener.local_addr().expect("addr"));
        let stop = CancellationToken::new();
        let stop2 = stop.clone();
        let task = tokio::spawn(async move {
            let _ = axum::serve(listener, app)
                .with_graceful_shutdown(async move { stop2.cancelled().await })
                .await;
        });
        Self {
            base,
            shared,
            stop,
            task: Some(task),
        }
    }

    /// `http://127.0.0.1:<port>`.
    #[must_use]
    pub fn base(&self) -> &str {
        &self.base
    }

    /// A full URL for a path (`/range/1000`).
    #[must_use]
    pub fn url(&self, path: &str) -> String {
        format!("{}{path}", self.base)
    }

    /// Every request so far.
    #[must_use]
    pub fn requests(&self) -> Vec<RecordedRequest> {
        self.shared.log.lock().unwrap().clone()
    }

    /// Requests to one exact path.
    #[must_use]
    pub fn requests_for(&self, path: &str) -> Vec<RecordedRequest> {
        self.requests()
            .into_iter()
            .filter(|r| r.path == path)
            .collect()
    }

    /// Requests to one exact path.
    #[must_use]
    pub fn hits(&self, path: &str) -> u32 {
        self.shared
            .hits
            .lock()
            .unwrap()
            .get(path)
            .copied()
            .unwrap_or(0)
    }

    /// Peak number of bodies in flight at once for a route prefix (`range`).
    #[must_use]
    pub fn max_concurrent(&self, prefix: &str) -> usize {
        self.shared
            .concurrent
            .lock()
            .unwrap()
            .get(prefix)
            .map_or(0, |e| e.1)
    }

    /// Peak number of bodies in flight at once across every route.
    #[must_use]
    pub fn max_concurrent_total(&self) -> usize {
        self.shared.total.lock().unwrap().1
    }

    /// Forgets the request log, hit counts and peaks.
    pub fn reset(&self) {
        self.shared.log.lock().unwrap().clear();
        self.shared.hits.lock().unwrap().clear();
        for e in self.shared.concurrent.lock().unwrap().values_mut() {
            e.1 = e.0;
        }
        let mut t = self.shared.total.lock().unwrap();
        t.1 = t.0;
    }

    /// Stops the server.
    pub async fn stop(mut self) {
        self.stop.cancel();
        if let Some(t) = self.task.take() {
            let _ = tokio::time::timeout(Duration::from_secs(5), t).await;
        }
    }
}

impl Drop for MediaServer {
    fn drop(&mut self) {
        self.stop.cancel();
        if let Some(t) = self.task.take() {
            t.abort();
        }
    }
}
